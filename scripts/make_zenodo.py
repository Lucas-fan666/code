def md5(path: Path) -> str:
    h = hashlib.md5()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def add_tree(z: zipfile.ZipFile, files: list[Path], prefix: str) -> int:
    from make_dist import canonical_names
    n = 0
    for p in files:
        rel = p.relative_to(ROOT).as_posix()
        z.write(p, arcname=canonical_names(f"{prefix}/{rel}"))
        n += 1
    return n


STUDY_STEMS = ["email-Eu-core", "facebook_combined", "ca-GrQc", "ca-HepTh",
               "ca-CondMat", "wiki-Vote", "p2p-Gnutella08", "email-Enron"]
HELD_OUT_STEMS = ["ca-HepPh", "ca-AstroPh", "as-caida20071105", "oregon1_010331",
                  "p2p-Gnutella24", "p2p-Gnutella31"]


def build_data() -> Path:
    proc = ROOT / "data" / "processed"
    edges = sorted(proc.glob("*.edges"))
    temporal = sorted(proc.glob("*.temporal.tsv"))
    main = [p for p in edges if p.stem in set(STUDY_STEMS)]

    out = OUT / "data_package.zip"
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        z.writestr("data/README.md", DATA_README)
        for p in edges + temporal:
            # paths are written by hand here, not by add_tree
            z.write(p, arcname=p.relative_to(ROOT).as_posix())
        for p in main:
            z.write(p, arcname=f"data/main_subset/{p.name}")
        held = [p for p in edges if p.stem in set(HELD_OUT_STEMS)]
        for p in held:
            z.write(p, arcname=f"data/held_out/{p.name}")
        manifests = [p for p in (ROOT / "data").iterdir() if p.suffix == ".json"]
        for p in manifests:
            z.write(p, arcname=f"data/{p.name}")
    print(f"  data_package.zip: {len(edges)} edge files, {len(temporal)} temporal files, "
          f"{len(main)} in main_subset, {len(held)} held out, "
          f"{out.stat().st_size / 1e6:.2f} MB")
    return out


def build_code() -> Path:
    files = collect()
    out = OUT / "code_package.zip"
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        add_tree(z, files, ARC)
    print(f"  code_package.zip: {len(files)} files, {out.stat().st_size / 1e6:.2f} MB")
    return out


def build_metadata(data_zip: Path, code_zip: Path) -> Path:
    sums = [f"{md5(p)}  {p.name}" for p in (data_zip, code_zip)]
    (OUT / "CHECKSUMS.md5").write_text("\n".join(sums) + "\n", encoding="utf-8")
    meta = {
        "upload_type": "dataset",
        "publication_type": None,
        "publication_date": DATE,
        "title": TITLE,
        "creators": [AUTHOR],
        "description": DESCRIPTION,
        "access_right": "open",
        "license": "mit",
        "language": "eng",
        "keywords": KEYWORDS,
        "related_identifiers": RELATED,
        "version": "1.0.0",
        "notes": ("Companion code is also on GitHub; see isSupplementedBy. "
                  "The manuscript PDF is attached for reference only."),
        "communities": [],
        "grants": [
            {"funder": {"name": "No funding received"},
             "title": "This research received no external funding"},
        ],
        "files": [
            {"name": data_zip.name, "size": data_zip.stat().st_size,
             "checksum": f"md5:{md5(data_zip)}"},
            {"name": code_zip.name, "size": code_zip.stat().st_size,
             "checksum": f"md5:{md5(code_zip)}"},
        ],
    }
    path = OUT / "metadata.json"
    path.write_text(json.dumps(meta, indent=2, ensure_ascii=False), encoding="utf-8")
    return path


def build_deposit(data_zip: Path, code_zip: Path, meta: Path) -> Path:
    """One file to drag into the Zenodo web form."""
    pdf = ROOT / "manuscript" / "main.pdf"
    out = OUT / "zenodo_deposit.zip"
    with zipfile.ZipFile(out, "w", compression=zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for p in (data_zip, code_zip, meta):
            z.write(p, arcname=p.name)
        built = ROOT / "manuscript" / "main_build.pdf"
        if built.exists() and built.stat().st_mtime > pdf.stat().st_mtime:
            z.write(built, arcname="manuscript.pdf")
        elif pdf.exists():
            z.write(pdf, arcname="manuscript.pdf")
    sums = [f"{md5(p)}  {p.name}" for p in (data_zip, code_zip, meta)]
    (OUT / "CHECKSUMS.md5").write_text("\n".join(sums) + "\n", encoding="utf-8")
    print(f"  zenodo_deposit.zip: {out.stat().st_size / 1e6:.2f} MB")
    return out


