def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for stale in OUT.glob("*.zip"):
        stale.unlink()
    data_zip = build_data()
    code_zip = build_code()
    meta = build_metadata(data_zip, code_zip)
    build_deposit(data_zip, code_zip, meta)
    build_note(data_zip, code_zip, meta)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()